"""``catalog.json`` writer (contracts.md §5).

The catalog is generated by ``publish``, never hand-edited. It indexes the single
``scores.parquet`` plus, per release / year / region / challenger, the insights
manifest url and the viewer zarr url. The assembled catalog is validated against
``catalog.schema.json`` before it is written; an invalid catalog is never emitted.
"""

from dataclasses import dataclass
from datetime import datetime, timezone
import json
from pathlib import Path

from oceanbench.core.schema_validation import validate_against_schema

CATALOG_FILENAME = "catalog.json"
CATALOG_SCHEMA_VERSION = "2.0"


@dataclass(frozen=True)
class CatalogEntry:
    """One (release, year, region, challenger) row of the catalog."""

    release: str
    year: str
    region: str
    challenger: str
    insights_manifest_url: str
    viewer_zarr_url: str


def _assemble_releases(entries: list[CatalogEntry]) -> dict:
    releases: dict[str, dict] = {}
    for entry in entries:
        challenger_entry = (
            releases.setdefault(entry.release, {"years": {}})["years"]
            .setdefault(entry.year, {"regions": {}})["regions"]
            .setdefault(entry.region, {})
        )
        if entry.challenger in challenger_entry:
            raise ValueError(
                f"Duplicate catalog entry for {entry.release}/{entry.year}/{entry.region}/{entry.challenger}."
            )
        challenger_entry[entry.challenger] = {
            "insights_manifest_url": entry.insights_manifest_url,
            "viewer_zarr_url": entry.viewer_zarr_url,
        }
    return releases


def build_catalog(
    entries: list[CatalogEntry],
    *,
    scores_url: str,
    challengers_url: str | None = None,
    generated_at: str | None = None,
) -> dict:
    """Assemble and validate a catalog dict from its entries (does not write it)."""
    if not entries:
        raise ValueError("A catalog needs at least one entry.")
    catalog = {
        "schema_version": CATALOG_SCHEMA_VERSION,
        "generated_at": generated_at or datetime.now(timezone.utc).isoformat(),
        "scores_url": scores_url,
        "releases": _assemble_releases(entries),
    }
    if challengers_url is not None:
        catalog["challengers_url"] = challengers_url
    validate_against_schema(catalog, "catalog")
    return catalog


def write_catalog(
    entries: list[CatalogEntry],
    output_directory: str,
    *,
    scores_url: str,
    challengers_url: str | None = None,
    generated_at: str | None = None,
) -> tuple[dict, str]:
    """Build, validate and write ``catalog.json``, returning ``(catalog, path)``."""
    catalog = build_catalog(
        entries,
        scores_url=scores_url,
        challengers_url=challengers_url,
        generated_at=generated_at,
    )
    output_directory_path = Path(output_directory)
    output_directory_path.mkdir(parents=True, exist_ok=True)
    catalog_path = output_directory_path / CATALOG_FILENAME
    catalog_path.write_text(json.dumps(catalog, sort_keys=True, indent=2), encoding="utf-8")
    return catalog, str(catalog_path)
